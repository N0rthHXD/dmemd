package observation

import (
	"errors"
	"strings"
	"time"

	"github.com/N0rthHXD/dmemd/internal/idgen"
	"github.com/N0rthHXD/dmemd/internal/source"
)

// ErrEmptyDraft marks a model item that carries neither a selectable span nor a
// usable normalized expression. Such an item cannot become an observation.
var ErrEmptyDraft = errors.New("observation: draft is empty")

// BuildFromDraft is the only entry point from model output into persistent L0
// observations. The model supplies span IDs and, optionally, one short
// normalized expression. Identity, source association, status, timestamps and
// all evidence fields are generated by this function.
//
// When the selected spans cannot be bound, a non-empty normalized expression is
// still retained as a pending observation; the binding failure is represented by
// the persisted status rather than by discarding the expression. A draft with
// neither content nor usable spans produces no observation and an error.
func BuildFromDraft(
	src source.Source,
	view source.View,
	draft Draft,
	modelVersion string,
	now time.Time,
) (Observation, []source.Evidence, error) {
	now = now.UTC()
	content := strings.TrimSpace(draft.Content)
	segments, spanErr := source.ResolveSegments(view, draft.SpanIDs)
	if spanErr != nil {
		if content == "" {
			return Observation{}, nil, spanErr
		}
		return Observation{
			ID:                idgen.NewUUID(),
			SourceID:          src.ID,
			ScopeKey:          src.ScopeKey,
			Kind:              resolvedKind(draft.Kind, content),
			Content:           content,
			ContentMode:       ContentNormalized,
			Status:            StatusPending,
			ExtractionVersion: modelVersion,
			CreatedAt:         now,
			UpdatedAt:         now,
		}, nil, nil
	}

	mode := ContentNormalized
	if content == "" {
		content = joinSegmentText(segments)
		mode = ContentExtractive
	}
	if content == "" {
		return Observation{}, nil, ErrEmptyDraft
	}
	ids := make([]string, 0, len(segments))
	for _, segment := range segments {
		ids = append(ids, segment.ID)
	}
	evidence := source.EvidenceForResolvedSegments(src, segments, ids, now)
	status := StatusObserved
	if len(evidence) == 0 || src.Redacted {
		status = StatusPending
	}
	return Observation{
		ID:                idgen.NewUUID(),
		SourceID:          src.ID,
		ScopeKey:          src.ScopeKey,
		Kind:              resolvedKind(draft.Kind, content),
		Content:           content,
		ContentMode:       mode,
		OriginRole:        originRole(segments),
		Status:            status,
		ExtractionVersion: modelVersion,
		CreatedAt:         now,
		UpdatedAt:         now,
	}, evidence, nil
}

func resolvedKind(kind Kind, content string) Kind {
	if kind.Known() {
		return kind
	}
	return inferKind(content)
}

// inferKind applies a conservative generic fallback when the model omitted the
// optional kind. It never reads report-specific vocabulary and defaults to fact.
func inferKind(content string) Kind {
	lower := strings.ToLower(content)
	if strings.Contains(lower, "先") && (strings.Contains(lower, "再") || strings.Contains(lower, "然后")) {
		return KindProcedure
	}
	if strings.Contains(lower, "步骤") || strings.Contains(lower, "first ") && strings.Contains(lower, "then ") {
		return KindProcedure
	}
	for _, cue := range []string{
		"喜欢", "不喜欢", "偏好", "希望", "更愿意", "宁愿", "默认",
		"prefer", "dislike", "like ", "would rather", "default",
	} {
		if strings.Contains(lower, cue) {
			return KindPreference
		}
	}
	return KindFact
}

func originRole(segments []source.Segment) string {
	for _, segment := range segments {
		if role := strings.TrimSpace(segment.Role); role != "" {
			return role
		}
	}
	return ""
}

func joinSegmentText(segments []source.Segment) string {
	parts := make([]string, 0, len(segments))
	for _, segment := range segments {
		if text := strings.TrimSpace(segment.Text); text != "" {
			parts = append(parts, text)
		}
	}
	return strings.Join(parts, "\n")
}
